/**
 * ONE animated button, as a sample (jdp, 2026-09-11: "Erst ein Muster zeigen").
 *
 * THE QUESTION BEHIND IT: a README button cannot react to the pointer. Four
 * ways were checked and all four are closed - GitHub's sanitiser strips <style>
 * and script, an inline style carries no pseudo-classes, an SVG loaded as <img>
 * never receives pointer events, and <picture> inside <a> is broken by the same
 * sanitiser. So hover is out.
 *
 * MOTION IS NOT. An SVG loaded as <img> still runs its own CSS animations, and
 * this account's profile banner has been proving that daily: the name shimmers
 * and the claim types itself, entirely inside the asset, with no third-party
 * service. This borrows that mechanism for a button.
 *
 * WHY THE ARTWORK IS AN EMBEDDED PNG rather than redrawn as vector: the button
 * carries a WORD, and an <img>-loaded SVG with a <text> element falls back to
 * whatever font the viewer's renderer happens to have - which is exactly why
 * the static buttons are PNGs in the first place. Embedding the finished PNG as
 * a data URI keeps the lettering byte-identical to the button beside it and
 * adds the motion on top. No network request, nothing to cache separately.
 *
 * CSS, NOT SMIL, for one reason: only CSS can be switched off by
 * prefers-reduced-motion. A person who has asked their system for less motion
 * has asked everything, and an animation that ignores it is a bug.
 *
 * Run: node donate/buttons/gen-live-sample.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dir = dirname(fileURLToPath(import.meta.url));

/** The vendor canvas every button in the row shares. */
const W = 841.9;
const H = 245.3;
const R = 38.2;

/** Which button gets the sample treatment. */
const SOURCE = "button-crypto.png";
const OUT = "button-crypto-live.svg";

const png = readFileSync(join(__dir, SOURCE)).toString("base64");

/**
 * The sheen: a soft band that crosses the button and then stays away.
 *
 * The long gap is the whole design. A button that shimmers constantly competes
 * with the text around it, and a README is mostly text; one pass every few
 * seconds reads as a surface catching the light, which is what a real button
 * does. The band is tilted, because a vertical wipe reads as a loading bar.
 *
 * White at low opacity rather than a colour: the band has to work on whatever
 * fill the button carries, and adding light is the one change that never
 * fights a brand colour. Low really does mean low - the first attempt at 0.42
 * over a 230-wide band washed the word out while it passed, which at the size
 * a README renders these (160px) reads as glare rather than as a highlight.
 */
const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     version="1.1" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <!-- Generated by gen-live-sample.mjs - do not hand-edit. -->
  <title>Donate with crypto</title>
  <defs>
    <clipPath id="edge">
      <rect x="0" y="0" width="${W}" height="${H}" rx="${R}" ry="${R}"/>
    </clipPath>
    <linearGradient id="sheen" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0"    stop-color="#fff" stop-opacity="0"/>
      <stop offset="0.45" stop-color="#fff" stop-opacity="0.28"/>
      <stop offset="0.55" stop-color="#fff" stop-opacity="0.28"/>
      <stop offset="1"    stop-color="#fff" stop-opacity="0"/>
    </linearGradient>
  </defs>
  <style>
    /* Off-canvas for most of the cycle, one pass, then away again. The whole
       travel happens in the first fifth of the loop; the rest is the pause. */
    @keyframes pass {
      0%   { transform: translateX(-460px); }
      18%  { transform: translateX(1020px); }
      100% { transform: translateX(1020px); }
    }
    .band { animation: pass 5.2s cubic-bezier(.4, 0, .3, 1) infinite; }
    /* Somebody who asked their system for less motion asked everything. */
    @media (prefers-reduced-motion: reduce) {
      .band { animation: none; opacity: 0; }
    }
  </style>
  <g clip-path="url(#edge)">
    <image x="0" y="0" width="${W}" height="${H}"
           xlink:href="data:image/png;base64,${png}"/>
    <g class="band">
      <!-- Tilted, and taller than the canvas, so the tilt never exposes a
           corner. skewX rather than rotate: the band stays axis-aligned for
           the translate, so the motion is one transform and not two. -->
      <rect x="-120" y="-60" width="165" height="${H + 120}"
            fill="url(#sheen)" transform="skewX(-16)"/>
    </g>
  </g>
</svg>
`;

writeFileSync(join(__dir, OUT), svg, "utf8");
console.log(`${OUT} geschrieben, ${Math.round(svg.length / 1024)} KB (davon ${Math.round(png.length / 1024)} KB Bild)`);
